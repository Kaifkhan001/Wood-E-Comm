#!/usr/bin/env node
// Generates drizzle-manual/<tag>.sql: the exact SQL of a drizzle-kit migration,
// wrapped in a transaction, plus the same row that `drizzle-kit migrate` would
// write to drizzle.__drizzle_migrations. Pasting the output into the Neon SQL
// Editor is then equivalent to running `npm run db:migrate` for that migration --
// the hash is computed exactly as node_modules/drizzle-orm/migrator.js does, so a
// later `db:migrate` run against the same database reports nothing to apply.
//
// Usage: node scripts/make-manual-migration.mjs 0001_slug_redirects [path/to/extra-backfill.sql]
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";

const tag = process.argv[2];
if (!tag) throw new Error("Usage: node scripts/make-manual-migration.mjs <migration-tag> [extra-sql-file]");
const extraSqlFile = process.argv[3];

const root = path.resolve(import.meta.dirname, "..");
const journal = JSON.parse(readFileSync(path.join(root, "drizzle/meta/_journal.json"), "utf8"));
const entry = journal.entries.find((e) => e.tag === tag);
if (!entry) throw new Error(`No journal entry for tag "${tag}". Run npm run db:generate first.`);

const migrationPath = path.join(root, `drizzle/${tag}.sql`);
const migrationSql = readFileSync(migrationPath, "utf8");
const hash = createHash("sha256").update(migrationSql).digest("hex");

const extraSql = extraSqlFile ? readFileSync(path.join(root, extraSqlFile), "utf8").trim() : "";

const out = `-- Run this BEFORE deploying the new code.
-- Equivalent to \`npm run db:migrate\` applying drizzle/${tag}.sql against this database.
-- Generated by scripts/make-manual-migration.mjs -- do not hand-edit the hash below.
BEGIN;

CREATE SCHEMA IF NOT EXISTS drizzle;
CREATE TABLE IF NOT EXISTS drizzle.__drizzle_migrations (
  id SERIAL PRIMARY KEY,
  hash text NOT NULL,
  created_at bigint
);

${migrationSql.trim()}
${extraSql ? `\n-- Data backfill\n${extraSql}\n` : ""}
INSERT INTO drizzle.__drizzle_migrations (hash, created_at) VALUES ('${hash}', ${entry.when});

COMMIT;
`;

const outDir = path.join(root, "drizzle-manual");
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
const outPath = path.join(outDir, `${tag}.sql`);
writeFileSync(outPath, out);
console.log(`Wrote ${outPath}`);
console.log(`hash=${hash} created_at=${entry.when}`);
